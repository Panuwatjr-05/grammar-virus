// "adverb" in English mode, "คำกริยาวิเศษณ์ (adverb)" in Thai mode
function posName(p, plural=false){
  const m = POS[p]; if(!m) return p;
  const en = plural ? m.pl : m.en;
  return (typeof Store!=='undefined' && Store.d && Store.d.settings.lang==='th') ? `${m.th} (${en})` : en;
}
// with an English article: "an adverb", "a noun" (Thai needs none)
function posA(p){
  const m = POS[p];
  if(m && m.one && !(Store.d && Store.d.settings.lang==='th')) return m.one;     // "a past simple verb"
  const n = posName(p);
  return /^[a-z]/.test(n) ? (/^[aeiou]/.test(n) ? 'an ' : 'a ') + n : n;
}

function T(key, ...args){
  const lang = (typeof Store!=='undefined' && Store.d && STR[Store.d.settings.lang]) ? Store.d.settings.lang : 'en';
  let s = STR[lang][key] ?? STR.en[key] ?? key;
  args.forEach((v,i)=>{ s = s.split('{'+i+'}').join(v); });
  return s;
}
